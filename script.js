const panel = document.getElementById('casePanel');
const backdrop = document.getElementById('panelBackdrop');
const content = document.getElementById('caseContent');
const closeBtn = document.querySelector('.panel-close');

function processBlock(data){
  if(!data.process || !data.process.length) return '';
  const cards = data.process.map(item => {
    const [step, title, body] = item;
    return `<div class="process-card"><span>${step}</span><h4>${title || ''}</h4><p>${body || ''}</p></div>`;
  }).join('');
  return `<div class="process-block"><h3>${data.processTitle || 'Process'}</h3><div class="process-grid">${cards}</div></div>`;
}

function metricsBlock(data){
  if(!data.metrics || !data.metrics.length) return '';
  return `<div class="metric-row">${data.metrics.map(([big,label]) => `<div class="metric"><b>${big || ''}</b><span>${label || ''}</span></div>`).join('')}</div>`;
}

