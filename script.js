function evidenceBlock(data){
  const visuals = data.images && data.images.length
    ? `<div class="evidence-grid">${data.images.map(([src,caption]) => `<figure><img src="${src}" alt="${caption || data.title}"><figcaption>${caption || ''}</figcaption></figure>`).join('')}</div>`
    : '';
  const docs = data.pdf ? `<div class="doc-links"><a href="${data.pdf}" target="_blank" rel="noopener">${data.pdfLabel || 'Open document'}</a></div>` : '';
  if(!visuals && !docs) return '';
  return `<div class="evidence"><h3>Selected evidence</h3>${visuals}${docs}</div>`;
}

function renderCase(data){
  if(!data) return;
  const note = data.note ? `<p class="note privacy-note">${data.note}</p>` : '';
  content.innerHTML = `
    <div class="case-head">
      <div class="label">${data.label || ''}</div>
      <h2>${data.title || ''}</h2>
      <p>${data.dek || ''}</p>
    </div>
    <div class="case-summary">
      <div><h3>Challenge</h3><p>${data.challenge || ''}</p></div>
      <div><h3>My contribution</h3><p>${data.contribution || ''}</p></div>
    </div>
    ${processBlock(data)}
    ${metricsBlock(data)}
    ${visualBlock(data.visual)}
    ${evidenceBlock(data)}
    ${note}
  `;
}

function openCase(key){
  renderCase(cases[key]);
  panel.classList.add('open');
  panel.setAttribute('aria-hidden','false');
  backdrop.classList.add('show');
  document.body.style.overflow='hidden';
}
function closeCase(){
  panel.classList.remove('open');
  panel.setAttribute('aria-hidden','true');
  backdrop.classList.remove('show');
  document.body.style.overflow='';
}

document.querySelectorAll('.project-row').forEach(btn => btn.addEventListener('click',() => openCase(btn.dataset.case)));
closeBtn.addEventListener('click',closeCase);
backdrop.addEventListener('click',closeCase);
document.addEventListener('keydown',e => { if(e.key === 'Escape') closeCase(); });
